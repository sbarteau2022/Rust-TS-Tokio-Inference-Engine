"""Generate committed Q60 constants deterministically with Decimal, not libm."""
from decimal import Decimal, localcontext
from pathlib import Path
import argparse


def constants():
    with localcontext() as ctx:
        ctx.prec = 90
        def atan(x):
            term, total, n = x, x, 1
            while True:
                term *= -x*x
                update = term / (2*n+1)
                if abs(update) < Decimal('1e-86'):
                    return total
                total += update
                n += 1
        pi = 16*atan(Decimal(1)/5)-4*atan(Decimal(1)/239)
        scale = Decimal(2)**60
        angles = [int((pi/4 if i == 0 else atan(Decimal(2)**-i))*scale/pi) for i in range(48)]
        hyper = [0]+[int(((1+Decimal(2)**-i)/(1-Decimal(2)**-i)).ln()*scale/2) for i in range(1,48)]
        gain = Decimal(1)
        for i in range(48):
            gain /= (1+Decimal(2)**(-2*i)).sqrt()
        return angles, hyper, int(gain*scale)


def source():
    a, h, gain = constants()
    def array(name, values):
        return f'pub const {name}: [i64; 48] = [\n'+''.join(f'    {x},\n' for x in values)+'];\n'
    return '// Generated by judges/generate_cordic.py using 90-digit Decimal arithmetic.\n'+array('ATAN_PI', a)+array('ATANH', h)+f'pub const CIRCULAR_GAIN: i64 = {gain};\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1]/'src/cordic_tables.rs'
    if args.check:
        assert target.read_text() == source(), 'CORDIC table drift'
    else:
        target.write_text(source())
